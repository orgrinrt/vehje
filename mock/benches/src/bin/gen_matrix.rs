fn residual_family() -> Vec<MatrixSpec> {
    // Isolate ONE axis, register/SSA vs stack-bytecode encoding, on the identical
    // program. Both cells must (a) run over the SAME decode form and (b) fold the
    // SAME live-out set, or the reported ratio is a composite of encoding + decode
    // form + checksum scope. So the register cell runs the PREDECODED interpreter
    // (matching that the stack cell runs a predecoded `Vec<Bc>`, not the wire form),
    // and BOTH fold `checksum_at` over the program's live-out sinks (equal element
    // count), instead of the register side paying a full-array fold and the stack
    // side a live-out-only fold. The earlier asymmetry burdened the register side,
    // so it understated register's real advantage; this makes the number clean.
    PROFILES.iter().map(|p| {
        let reg_prep = format!(
            "static PREP: OnceLock<(c::predecode::Predecoded, Vec<u32>)> = OnceLock::new(); \
             let (pd, sink_ids) = PREP.get_or_init(|| {{ let mut gp = c::GenParams::profile(\"{p}\").unwrap(); gp.node_count = N; let prog = c::generate(&gp); let sinks = c::optimize::sinks(&prog); let bytes = c::ir::encode(&prog, &c::ir::REC24); let d = c::ir::Decoded::parse(&bytes, c::ir::REC24).unwrap(); (c::predecode::predecode(&d), sinks) }}); \
             let mut r = vec![0u64; pd.nodes.len()];"
        );
        let cells = vec![
            cell("register", reg_prep, "c::predecode::interpret_predecoded(pd, seed, &mut r); acc ^= c::access::checksum_at(&r, sink_ids);".to_string(), &[]),
            cell(
                "stack",
                format!("static PREP: OnceLock<c::stackbc::StackProgram> = OnceLock::new(); let sp = PREP.get_or_init(|| {{ let mut gp = c::GenParams::profile(\"{p}\").unwrap(); gp.node_count = N; c::stackbc::compile(&c::generate(&gp)) }}); let mut st = vec![0u64; 64]; let mut lo = vec![0u64; sp.num_locals];"),
                "c::stackbc::interpret_stack(sp, seed, &mut st, &mut lo); acc ^= c::access::checksum_at(&lo, &sp.out_locals);".to_string(),
                &[],
            ),
        ];
        spec(format!("carrier_residual_{p}"), format!("Residual encoding: predecoded register/SSA vs stack bytecode, {p} profile"), "register", &format!("carrier_res_{p}"), cells)
    }).collect()
}

fn optimize_family() -> Vec<MatrixSpec> {
    // (tag, cse, fold, dce, eqsat, canon): the shipped optimize axis is
    // none / CSE / fold / DCE / canon / all, each measured by the DOWNSTREAM interp
    // cost over the resulting (possibly smaller) program. eqsat is dropped from the
    // default set: the review panel replicated that `cse+eqsat` equals `eqsat` in
    // node count on every profile (CSE recovers nothing eqsat lost) and that eqsat's
    // marginal contribution inside the full pipeline is zero or negative everywhere,
    // standalone inflating madd 5.6x. `canon` (commutative-operand canonicalization
    // + CSE) is the cheap subset of what AC-reassociation was for, and `all` now
    // means CSE + fold + DCE + canon. eqsat stays in the optimize() API, parked for
    // a consumer whose residuals carry long literal AC chains.
    let strategies: &[(&str, bool, bool, bool, bool, bool)] = &[
        ("none", false, false, false, false, false),
        ("cse", true, false, false, false, false),
        ("fold", false, true, false, false, false),
        ("dce", false, false, true, false, false),
        ("canon", true, false, false, false, true),
        ("all", true, true, true, false, true),
    ];
    PROFILES.iter().map(|p| {
        let cells = strategies.iter().map(|(tag, cse, fold, dce, eqsat, canon)| {
            // cache the ENCODED optimized program + its live-out ids: optimize()
            // (incl the eqsat saturation) and encode are O(N) and would otherwise
            // rerun on every timed sample. Only the cheap Decoded::parse + results
            // alloc stay per-call. checksum_at over the live-outs keeps the changed
            // node count comparable across strategies.
            let prep = format!(
                "static PREP: OnceLock<(Vec<u8>, Vec<u32>)> = OnceLock::new(); \
                 let (bytes, out_ids) = PREP.get_or_init(|| {{ let mut gp = c::GenParams::profile(\"{p}\").unwrap(); gp.node_count = N; let prog = c::generate(&gp); let opt = c::optimize::optimize(&prog, {cse}, {fold}, {dce}, {eqsat}, {canon}); (c::ir::encode(&opt.prog, &c::ir::REC24), opt.out_ids) }}); \
                 let d = c::ir::Decoded::parse(bytes, c::ir::REC24).unwrap(); \
                 let mut r = vec![0u64; d.node_count.max(1)];"
            );
            cell(tag, prep, "c::interpret(&d, seed, &mut r); acc ^= c::access::checksum_at(&r, out_ids);".to_string(), &[])
        }).collect();
        spec(format!("carrier_optimize_{p}"), format!("Optimize stage (none/CSE/eqsat/CSE+eqsat...), downstream interp, {p} profile"), "none", &format!("carrier_opt_{p}"), cells)
    }).collect()
}

fn native_family() -> Vec<MatrixSpec> {
    // The near-native tier: interp vs direct native codegen vs copy-and-patch
    // stencil, per profile. copypatch/stencil are jit (aarch64+macos) only.
    PROFILES.iter().map(|p| {
        let jit_prep = format!("{} let mut r = vec![0u64; prog.nodes.len()];", program_prep(p));
        // Tags name the technique per Xu & Kjolstad (OOPSLA 2021): `direct` is
        // per-node instruction selection (copypatch.rs `JitCode`); `copypatch` is
        // the actual copy-and-patch stencil mechanism (stencil.rs `StencilCode`,
        // memcpy + imm12 hole-patch, no per-node isel). The earlier tags inverted
        // this (the direct-codegen cell was tagged "copypatch").
        let cells = vec![
            cell("interp", wire_prep(p, "REC24"), "c::interpret(&d, seed, &mut r); acc ^= c::checksum(&r);".to_string(), &[]),
            cell("direct", format!("{jit_prep} let jit = c::copypatch::JitCode::new(prog).expect(\"jit\");"), "jit.run(seed, &mut r); acc ^= c::checksum(&r);".to_string(), &["jit"]),
            cell("copypatch", format!("{jit_prep} let jit = c::stencil::StencilCode::new(prog).expect(\"jit\");"), "jit.run(seed, &mut r); acc ^= c::checksum(&r);".to_string(), &["jit"]),
        ];
        // sizes capped below the JIT imm12 window (node/const index < 4096): the
        // copypatch/stencil constructors decline (return None) above it, so 4096
        // and 16384 are out of range for those two techniques. Declared out of
        // range rather than discovered by a crash (the mandate: name it, do not
        // silently drop it).
        spec_sized(format!("carrier_native_{p}"), format!("Near-native tier: interp vs direct codegen vs copy-and-patch stencil, {p} profile (JIT window caps sizes at 1024)"), "interp", &format!("carrier_nat_{p}"), cells, vec![64, 256, 1024])
    }).collect()
}

fn vertical_family() -> Vec<MatrixSpec> {
    // SoA/SIMD amortization. Every cell processes EXACTLY 8 inputs per timed call
    // (scalar: 8 scalar passes; vert4: two W=4 passes; vert8: one W=8 pass), so the
    // raw per-call times are directly comparable and subtract-mode is correct with
    // NO per-input divisor to remember. The SoA scratch is pre-allocated in prep
    // and reused (via `make_scratch` + the non-allocating `..._into`), so no
    // allocation is charged to the timed region (the scalar baseline reuses its
    // buffer identically). vertical needs the `vertical` feature (portable_simd).
    PROFILES.iter().map(|p| {
        // pd + a reusable W-wide SoA scratch, allocated once outside the timed loop.
        let vprep = |w: usize| format!(
            "static PREP: OnceLock<c::predecode::Predecoded> = OnceLock::new(); \
             let pd = PREP.get_or_init(|| {{ let mut gp = c::GenParams::profile(\"{p}\").unwrap(); gp.node_count = N; let bytes = c::ir::encode(&c::generate(&gp), &c::ir::REC24); let d = c::ir::Decoded::parse(&bytes, c::ir::REC24).unwrap(); c::predecode::predecode(&d) }}); \
             let mut soa = c::vertical::make_scratch::<{w}>(pd.nodes.len());"
        );
        let cells = vec![
            // scalar reference: 8 PREDECODED scalar interprets per call, reusing `r`.
            // The vert cells run over cached `Predecoded`; the baseline must too, so
            // the only measured difference is scalar-lanes vs SIMD-lanes and NOT the
            // per-node wire decode the vert cells never pay (that decode-in-baseline
            // asymmetry inflated the reported vert8 win from an honest ~4.8x to ~6x).
            cell(
                "scalar",
                predecode_prep(p),
                "for j in 0..8u64 { let s = seed ^ j.wrapping_mul(0x9e37_79b9); c::predecode::interpret_predecoded(&pd, s, &mut r); acc ^= c::checksum(&r); }".to_string(),
                &[],
            ),
            // vert4: two W=4 passes = 8 inputs, reusing the pre-allocated scratch.
            cell(
                "vert4",
                vprep(4),
                "for pass in 0..2u64 { let mut s = [0u64; 4]; for (l, x) in s.iter_mut().enumerate() { *x = seed ^ (pass * 4 + l as u64).wrapping_mul(0x9e37_79b9); } acc ^= c::vertical::interpret_vertical_checksum_into::<4>(pd, &s, &mut soa); }".to_string(),
                &["vertical"],
            ),
            // vert8: one W=8 pass = 8 inputs.
            cell(
                "vert8",
                vprep(8),
                "let mut s = [0u64; 8]; for (l, x) in s.iter_mut().enumerate() { *x = seed ^ (l as u64).wrapping_mul(0x9e37_79b9); } acc ^= c::vertical::interpret_vertical_checksum_into::<8>(pd, &s, &mut soa);".to_string(),
                &["vertical"],
            ),
        ];
        spec(format!("carrier_vertical_{p}"), format!("Vertical/SoA SIMD, 8 inputs per call for every cell (scalar 8x1 vs vert4 2x4 vs vert8 1x8; directly comparable), {p} profile"), "scalar", &format!("carrier_vert_{p}"), cells)
    }).collect()
}

fn native_ceiling_family() -> Vec<MatrixSpec> {
    // The native ceiling floor over the madd-chain program (not a profile): the
    // interpreter vs the shape-specialized native loop, same program bytes.
    let prep = "static PREP: OnceLock<Vec<u8>> = OnceLock::new(); let bytes = PREP.get_or_init(|| c::madd_bytes(N / 4, c::ir::REC24)); let d = c::ir::Decoded::parse(bytes, c::ir::REC24).unwrap(); let mut r = vec![0u64; d.node_count];";
    let cells = vec![
        cell("interp", prep.to_string(), "for &b in input.iter() { c::interpret(&d, b as u64, &mut r); acc ^= c::checksum(&r); }".to_string(), &[]),
        cell("native", prep.to_string(), "acc ^= c::native_madd_over_input(&d, input, &mut r);".to_string(), &[]),
    ];
    // CAVEAT: unlike every other family (one program execution per iteration,
    // O(N) work), this family's body sweeps the whole N-byte input against a
    // size-N program, so its work is O(N) executions x O(N) program = O(N^2), a
    // THROUGHPUT-over-a-byte-stream measurement, not per-execution latency. Its
    // raw ns are NOT on the sibling families' scale and must never be normalized
    // against them. This shape is intentional (the crate's run_over_input /
    // native_madd_over_input ceiling idiom); do not reshape it. Sizes stop at
    // 1024 (matching the JIT native_family): N=4096 is 16x the node-step work of
    // N=1024 and, with calibrated repeats, exceeds even the 600s driver window
    // for no additional insight over the 64/256/1024 throughput-ceiling curve.
    vec![spec_sized("carrier_native_ceiling".to_string(), "Native ceiling: interpreter vs shape-specialized native madd loop (THROUGHPUT over a byte stream, O(N^2), not comparable to sibling per-execution numbers)".to_string(), "interp", "carrier_ceil", cells, vec![64, 256, 1024])]
}

fn main() {
    let out_dir = Path::new(".");
    let mut all: Vec<MatrixSpec> = Vec::new();
    all.extend(wire_family());
    all.extend(predecode_family());
    all.extend(cfg_family());
    all.extend(layout_family());
    all.extend(valrepr_family());
    all.extend(residual_family());
    all.extend(optimize_family());
    all.extend(native_family());
    all.extend(vertical_family());
    all.extend(native_ceiling_family());

    let mut sections: Vec<String> = Vec::new();
    let mut nvariants = 0usize;
    for s in &all {
        let bench = s.bench.clone();
        match generate(s, out_dir) {
            Ok(section) => {
                let count = section.matches("/target/release/").count() / SIZES.len();
                nvariants += count;
                println!("generated {bench}");
                sections.push(section);
            }
            Err(e) => {
                eprintln!("FAILED {bench}: {e}");
                std::process::exit(1);
            }
        }
    }

    let toml_path = Path::new("bench.toml");
    let marker = "# >>> carrier_matrix (generated by gen_matrix)";
    let existing = std::fs::read_to_string(toml_path).unwrap_or_default();
    let base = match existing.split_once(marker) {
        Some((before, _)) => before.trim_end().to_string(),
        None => existing.trim_end().to_string(),
    };
    let body = format!("{base}\n\n{marker}\n{}\n", sections.join("\n"));
    std::fs::write(toml_path, body).expect("write bench.toml");
    println!("\n{} benches, ~{} variants; appended sections to bench.toml", all.len(), nvariants);
}
