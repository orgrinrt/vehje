#!/usr/bin/env python3
"""Generate the value-representation bench: static/raw vs runtime-tagged vs
NaN-boxed, the carrier's fourth variant axis. The same mixed int/float program
is interpreted three ways; all fold the identical checksum (cross-validated), so
the measured gap is the cost of carrying a runtime type tag (dynamic typing) vs
knowing the type statically (what vehje's graded type system could prove).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SIZES = [64, 256, 1024, 4096, 16384]
REV = "49ff5f55b8413f7046281ae1944130c10509c361"

# (tag, buffer decls, call expr)
VARIANTS = [
    ("static", "let mut sc = vec![0u64; prog.len()];", "interp_static(prog, seed, &mut sc)"),
    ("tagged", "let mut tg = vec![0u8; prog.len()];\n    let mut bt = vec![0u64; prog.len()];", "interp_tagged(prog, seed, &mut tg, &mut bt)"),
    ("nanbox", "let mut nb = vec![0u64; prog.len()];", "interp_nanbox(prog, seed, &mut nb)"),
]

CARGO = """\
[workspace]
[package]
name = "{name}"
version = "0.0.0"
edition = "2021"
publish = false
[lib]
name = "{name}"
path = "src/lib.rs"
crate-type = ["cdylib"]
[dependencies]
mockspace-bench-core = {{ git = "https://github.com/hiisi-digital/mockspace", rev = "{rev}", features = ["std"] }}
mockspace-bench-macro = {{ git = "https://github.com/hiisi-digital/mockspace", rev = "{rev}" }}
vehje-bench-carrier = {{ path = "../../carrier" }}
[profile.release]
opt-level = 3
lto = "fat"
codegen-units = 1
"""

LIB = """\
// AUTO-GENERATED by gen_carrier_valrepr.py. Value representation: {tag}.
// The mixed int/float program is built once per subprocess (OnceLock, not
// const-foldable); the value buffers are allocated once per run; the timed
// region folds the FFI input byte per iteration so nothing hoists. All three
// representations fold the identical checksum, so the harness cross-validates
// them and the measured gap is the representation cost alone.
use mockspace_bench_core::{{timed, FfiBenchCall}};
use mockspace_bench_macro::bench_variant;
use std::sync::OnceLock;
use vehje_bench_carrier::valrepr::{{gen_valprog, interp_static, interp_tagged, interp_nanbox, VNode}};

static PROG: OnceLock<Vec<VNode>> = OnceLock::new();
const ITERS: usize = 16;

#[bench_variant("{name}", sizes = [64, 256, 1024, 4096, 16384])]
fn run<const N: usize>(input: &[u8; N], output: &mut [u8; 8]) -> FfiBenchCall {{
    let prog = PROG.get_or_init(|| gen_valprog(N, 0x7a1_5eed_0000_0001 ^ N as u64));
    {decls}
    timed! {{ run {{
        let mut acc: u64 = 0;
        for k in 0..ITERS {{
            let seed = (input[k % N] as i32) ^ (k as i32);
            acc ^= {call};
        }}
        output.copy_from_slice(&acc.to_le_bytes());
    }} }}
}}
"""


def main():
    names = []
    for tag, decls, call in VARIANTS:
        name = f"valrepr_{tag}"
        names.append(name)
        d = os.path.join(HERE, "variants", name, "src")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(HERE, "variants", name, "Cargo.toml"), "w") as f:
            f.write(CARGO.format(name=name, rev=REV))
        with open(os.path.join(d, "lib.rs"), "w") as f:
            f.write(LIB.format(name=name, tag=tag, decls=decls, call=call))
    paths = ", ".join(f'"variants/{n}/target/release/{n}"' for n in names)
    out = [
        "# >>> valrepr (generated)",
        "[bench.valrepr]",
        'title = "Value representation: static/raw vs runtime-tagged vs NaN-boxed (dynamic-typing cost)"',
        'workload = "realistic"',
        "master_seed = 0x5eed_7a10_0000_0001",
        "[bench.valrepr.normalise]",
        'baseline = "valrepr_static"',
        'mode = "subtract"',
    ]
    for n in SIZES:
        out += [f"[[bench.valrepr.sizes]]", f"n = {n}", f"variants = [{paths}]"]
    os.makedirs(os.path.join(HERE, "carrier_fragments"), exist_ok=True)
    with open(os.path.join(HERE, "carrier_fragments", "valrepr.toml"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("variants:", " ".join(names))
    print("wrote carrier_fragments/valrepr.toml")


if __name__ == "__main__":
    main()
